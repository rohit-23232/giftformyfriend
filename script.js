function setLanguage(lang){
  localStorage.setItem("friendSiteLang",lang);
  document.documentElement.lang = lang === "hi" ? "hi" : "en";
  document.body.classList.toggle("hi",lang==="hi");
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(translations[lang][key] !== undefined) el.textContent=translations[lang][key];
  });
  document.querySelectorAll("[data-lang]").forEach(el=>{
    el.classList.toggle("active",el.dataset.lang===lang);
  });
}

document.addEventListener("DOMContentLoaded",()=>{
  const saved=localStorage.getItem("friendSiteLang") || "en";
  setLanguage(saved);
  document.querySelectorAll("[data-lang]").forEach(btn=>{
    btn.addEventListener("click",()=>setLanguage(btn.dataset.lang));
  });

  const hearts=document.querySelector(".hearts");
  if(hearts){
    for(let i=0;i<22;i++){
      const h=document.createElement("span");
      h.className="heart";
      h.textContent=Math.random()>.5?"❤️":"♡";
      h.style.left=(Math.random()*100)+"%";
      h.style.fontSize=(12+Math.random()*24)+"px";
      h.style.animationDuration=(7+Math.random()*9)+"s";
      h.style.animationDelay=(-Math.random()*12)+"s";
      hearts.appendChild(h);
    }
  }
});

function toggleMenu(){
  const menu=document.querySelector(".navlinks");
  if(menu) menu.classList.toggle("open");
}

document.addEventListener("DOMContentLoaded",()=>{
  const current=location.pathname.split("/").pop() || "index.html";
  document.querySelectorAll(".navlinks a").forEach(a=>{
    a.classList.toggle("active",a.getAttribute("href")===current);
    a.addEventListener("click",()=>document.querySelector(".navlinks")?.classList.remove("open"));
  });
});

document.addEventListener("click",(e)=>{
  if(e.target.closest(".lang") || e.target.closest(".menu-toggle")) return;
  const symbols=["❤️","💖","✨","🌹","💕","💗","♡","🌸"];
  const el=document.createElement("span");
  el.className="click-pop";
  el.textContent=symbols[Math.floor(Math.random()*symbols.length)];
  el.style.left=e.clientX+"px";
  el.style.top=e.clientY+"px";
  document.body.appendChild(el);
  setTimeout(()=>el.remove(),800);
});
